#!/usr/bin/env node
// Apply SidekickDB's package rename (PR #7) to a working tree or to a set of
// files, honouring the allowlist and excluded paths in ./rename.mjs.
//
// Usage (from anywhere inside the repository):
//   node scripts/upstream/normalize-rename.mjs --all [--check]
//   node scripts/upstream/normalize-rename.mjs --changed <base>..<tip> [--check]
//   node scripts/upstream/normalize-rename.mjs [--check] <file>...
//   node scripts/upstream/normalize-rename.mjs --stdin --path <file>   (filter)
//
// Options:
//   --check            Do not write. Exit 1 if any file would change.
//   --lockfile MODE    auto (default): run `pnpm install --lockfile-only` in
//                      client/ when a workspace package.json changed.
//                      always | never.
//   --strict           Exit 2 if leftovers (old names that need a person to
//                      decide) are found.
//   --no-leftovers     Do not report leftovers.
//   --verbose, -v      Print every rewritten line.
//   --json <file>      Write a machine-readable summary.
//
// Lockfiles are never edited as text; they are regenerated by pnpm.
// Excluded paths (server/, self-hosting/, .github/, the Python package,
// essays and archived emails, LICENSE, ...) are never read or written.

import fs from 'node:fs';
import path from 'node:path';
import { git, lines, repoRoot, run } from './git.mjs';
import {
  isBinary,
  isExcluded,
  isWorkspacePackageJson,
  normalizeText,
  scanLeftovers,
} from './rename.mjs';

function parseArgs(argv) {
  const o = {
    all: false,
    changed: null,
    stdin: false,
    path: null,
    check: false,
    lockfile: 'auto',
    strict: false,
    leftovers: true,
    verbose: false,
    json: null,
    files: [],
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--all') o.all = true;
    else if (a === '--changed') o.changed = argv[++i];
    else if (a === '--stdin') o.stdin = true;
    else if (a === '--path') o.path = argv[++i];
    else if (a === '--check') o.check = true;
    else if (a === '--lockfile') o.lockfile = argv[++i];
    else if (a === '--strict') o.strict = true;
    else if (a === '--no-leftovers') o.leftovers = false;
    else if (a === '--verbose' || a === '-v') o.verbose = true;
    else if (a === '--json') o.json = argv[++i];
    else if (a === '-h' || a === '--help') {
      const src = fs.readFileSync(new URL(import.meta.url), 'utf8');
      process.stdout.write(
        src
          .split('\n')
          .slice(1)
          .filter((l) => l.startsWith('//'))
          .map((l) => l.replace(/^\/\/ ?/, ''))
          .join('\n') + '\n',
      );
      process.exit(0);
    } else if (a === '--') o.files.push(...argv.slice(i + 1)), (i = argv.length);
    else if (a.startsWith('-')) throw new Error(`unknown option ${a}`);
    else o.files.push(a);
  }
  if (!['auto', 'always', 'never'].includes(o.lockfile)) {
    throw new Error('--lockfile must be auto, always or never');
  }
  return o;
}

/** Repository-relative POSIX paths to process. */
export function collectFiles(o, root) {
  let files = [];
  if (o.all) files.push(...lines(git(['ls-files', '-z'], { cwd: root }).replace(/\0/g, '\n')));
  if (o.changed) {
    files.push(
      ...lines(
        git(['diff', '--name-only', '--no-renames', '-z', '--diff-filter=d', o.changed], {
          cwd: root,
        }).replace(/\0/g, '\n'),
      ),
    );
  }
  for (const f of o.files) {
    const abs = path.resolve(f);
    const rel = path.relative(root, abs).split(path.sep).join('/');
    if (fs.existsSync(abs) && fs.statSync(abs).isDirectory()) {
      files.push(...lines(git(['ls-files', '-z', '--', rel], { cwd: root }).replace(/\0/g, '\n')));
    } else files.push(rel);
  }
  return [...new Set(files)].sort();
}

/**
 * Normalize files in place (or just report with check=true).
 * @returns {{changed: {file, changes}[], leftovers: {file, items}[], skipped: number}}
 */
export function normalizeFiles(files, { root, check = false, leftovers = true } = {}) {
  const result = { changed: [], leftovers: [], skipped: 0 };
  for (const file of files) {
    if (isExcluded(file)) {
      result.skipped++;
      continue;
    }
    const abs = path.join(root, file);
    let buf;
    try {
      const st = fs.lstatSync(abs);
      if (!st.isFile()) continue; // symlinks, submodules, deleted files
      buf = fs.readFileSync(abs);
    } catch {
      continue;
    }
    if (isBinary(buf)) continue;
    const text = buf.toString('utf8');
    const { text: next, changes } = normalizeText(file, text);
    if (changes.length) {
      result.changed.push({ file, changes });
      if (!check) fs.writeFileSync(abs, next);
    }
    if (leftovers) {
      const items = scanLeftovers(file, check ? next : next);
      if (items.length) result.leftovers.push({ file, items });
    }
  }
  return result;
}

/** Regenerate client/pnpm-lock.yaml through pnpm (never by editing it). */
export function regenerateLockfile(root, { quiet = false } = {}) {
  const client = path.join(root, 'client');
  if (!quiet) console.log('Regenerating client/pnpm-lock.yaml with pnpm install --lockfile-only');
  // pnpm switches to the version pinned in client/package.json
  // ("packageManager") by itself. --ignore-scripts: no lifecycle scripts run.
  run('pnpm', ['install', '--lockfile-only', '--ignore-scripts', '--prefer-offline'], {
    cwd: client,
    stdio: ['ignore', quiet ? 'pipe' : 'inherit', 'inherit'],
    env: {
      TURBO_TELEMETRY_DISABLED: '1',
      NEXT_TELEMETRY_DISABLED: '1',
      npm_config_update_notifier: 'false',
    },
  });
}

export function printReport(result, { verbose = false, check = false, out = console.log } = {}) {
  const log = out;
  const verb = check ? 'would change' : 'changed';
  const n = result.changed.reduce((a, c) => a + c.changes.length, 0);
  log(`Rename normalizer: ${result.changed.length} file(s) ${verb}, ${n} rewrite(s).`);
  for (const { file, changes } of result.changed) {
    const rules = [...new Set(changes.map((c) => c.rule))].join(', ');
    log(`  ${file} (${changes.length}: ${rules})`);
    if (verbose) {
      for (const c of changes) {
        log(`    ${c.line}: - ${c.before.trim()}`);
        log(`    ${c.line}: + ${c.after.trim()}`);
      }
    }
  }
  const nl = result.leftovers.reduce((a, c) => a + c.items.length, 0);
  if (nl) {
    log(`\nLeftovers needing a decision: ${nl} in ${result.leftovers.length} file(s).`);
    for (const { file, items } of result.leftovers) {
      for (const it of items) {
        log(`  ${file}:${it.line} [${it.id}] ${it.text}`);
        log(`      -> ${it.hint}`);
      }
    }
  } else {
    log('Leftovers needing a decision: none.');
  }
}

function main() {
  const o = parseArgs(process.argv.slice(2));
  if (o.stdin) {
    if (!o.path) throw new Error('--stdin needs --path <file>');
    const input = fs.readFileSync(0);
    if (isBinary(input)) return process.stdout.write(input);
    process.stdout.write(normalizeText(o.path, input.toString('utf8')).text);
    return;
  }
  const root = repoRoot();
  if (!o.all && !o.changed && !o.files.length) {
    throw new Error('nothing to do: pass --all, --changed <range> or files (see --help)');
  }
  const files = collectFiles(o, root);
  const result = normalizeFiles(files, { root, check: o.check, leftovers: o.leftovers });
  printReport(result, { verbose: o.verbose, check: o.check });

  const pkgChanged = result.changed.some((c) => isWorkspacePackageJson(c.file));
  if (o.check) {
    if (pkgChanged) console.log('A workspace package.json would change: the lockfile would be regenerated.');
  } else if (o.lockfile === 'always' || (o.lockfile === 'auto' && pkgChanged)) {
    regenerateLockfile(root);
  }
  if (o.json) {
    fs.writeFileSync(o.json, JSON.stringify({ files: files.length, ...result }, null, 2));
  }
  if (o.check && result.changed.length) process.exitCode = 1;
  else if (o.strict && result.leftovers.length) process.exitCode = 2;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('normalize-rename.mjs')) {
  try {
    main();
  } catch (e) {
    console.error(`normalize-rename: ${e.message}`);
    process.exit(3);
  }
}
